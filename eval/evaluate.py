"""Measure quickcheck against the databricks-sql-corpus.

Two directions, as in the corpus harness itself:

    false positives -- any error on SQL known to be valid. The corpus's valid
                       sources and the reference must-parse cases. This is the
                       number that decides whether the checker is usable: a
                       red squiggle on good SQL, on every keystroke, is worse
                       than no checker at all. Target: zero.
    catch rate      -- share of guaranteed-invalid mutants flagged. Mutants are
                       generated by the corpus's own mutate.py from the valid
                       files, so they are the same ones SQLFluff is scored on.

The reference must-reject cases are reported too, but are not a target: they
are grammar-level omissions (a required clause left out), which a structural
checker is not built to see. That is SQLFluff's job.

Run with the corpus venv, which has the corpus package and SQLFluff's lexer:

    ../databricks-sql-corpus/.venv/bin/python eval/evaluate.py
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re
import statistics
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]


class Quickcheck:
    """The CLI in --jsonl batch mode: one node process for the whole run."""

    def __init__(self, warnings: bool = True) -> None:
        cmd = ["node", str(ROOT / "out" / "cli.js"), "--jsonl"]
        if not warnings:
            cmd.append("--no-warnings")
        self.proc = subprocess.Popen(
            cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, encoding="utf-8"
        )

    def check(self, text: str, ident: str = "") -> tuple[list[dict], float]:
        assert self.proc.stdin and self.proc.stdout
        self.proc.stdin.write(json.dumps({"id": ident, "text": text}) + "\n")
        self.proc.stdin.flush()
        reply = json.loads(self.proc.stdout.readline())
        return reply["diagnostics"], reply["micros"]

    def close(self) -> None:
        if self.proc.stdin:
            self.proc.stdin.close()
        self.proc.wait()


def errors_of(diags: list[dict]) -> list[dict]:
    return [d for d in diags if d["severity"] == "error"]


def warnings_of(diags: list[dict]) -> list[dict]:
    return [d for d in diags if d["severity"] == "warning"]


_STATEMENT_BREAK = re.compile(r";|^--\s*COMMAND\s*-{2,}\s*$", re.M)
_LEADING_COMMENTS = re.compile(r"\A(?:\s*(?:--[^\n]*|/\*.*?\*/))*\s*", re.S)


def in_raw_set(original: str, mutant: str) -> bool:
    """True when the mutation lands in a `SET key = value` statement.

    Spark reads a SET value as raw text (`SET k = dynamic,,static` is valid),
    and `SET k =` with an empty value is valid too, so these mutants are not
    guaranteed-invalid whatever mutate.py's tier says. mutate.py already means
    to skip the dangling `=` case (`_in_set_statement`) but misses a SET that
    follows a notebook header. `SET VAR` is real SQL and is kept.
    """
    pos = next((i for i, (a, b) in enumerate(zip(original, mutant)) if a != b), len(mutant))
    prefix = original[:pos]
    starts = [m.end() for m in _STATEMENT_BREAK.finditer(prefix)]
    statement = prefix[starts[-1] if starts else 0:]
    statement = _LEADING_COMMENTS.sub("", statement, count=1)
    words = statement.split(None, 2)
    return bool(words) and words[0].upper() == "SET" and (
        len(words) < 2 or words[1].upper() not in ("VAR", "VARIABLE")
    )


def show(d: dict) -> str:
    return f"{d['line']}:{d['column']} {d['severity']} [{d['code']}] {d['message'][:110]}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default=str(ROOT.parent / "databricks-sql-corpus"))
    ap.add_argument("--mutations", type=int, default=0, help="mutation budget (0 = all)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--sqlfluff-sample", type=int, default=0,
                    help="also time SQLFluff on this many corpus files, for comparison")
    ap.add_argument("--list", type=int, default=15, help="how many findings to print per section")
    args = ap.parse_args()

    corpus = pathlib.Path(args.corpus).resolve()
    sys.path.insert(0, str(corpus / "src"))
    from dbsqlparse.corpus.harness import CACHE_DIR, iter_sql_files, looks_like_json
    from dbsqlparse.corpus.mutate import GUARANTEED, mutate_corpus
    from dbsqlparse.corpus.reference import load_reference
    from dbsqlparse.corpus.sources import REMOTE_SOURCES

    qc = Quickcheck()
    results: dict = {"sources": {}, "reference": {}, "mutation": {}}

    # --- 1. false positives on valid SQL ---------------------------------------
    print("== valid corpus: any error is a false positive ==")
    print(f"{'source':26s} {'files':>6s} {'err files':>10s} {'warn files':>11s}")
    seeds: list[tuple[str, str]] = []
    fp_files: list[tuple[str, list[dict]]] = []
    warn_files: list[tuple[str, list[dict]]] = []
    timings: list[tuple[float, int]] = []
    for source in REMOTE_SOURCES:
        root = CACHE_DIR / source.name
        if source.expectation != "valid" or not root.exists():
            continue
        n = err = warn = 0
        for path in iter_sql_files(root):
            text = path.read_text(encoding="utf-8", errors="replace")
            if looks_like_json(text):
                continue
            diags, micros = qc.check(text, str(path))
            timings.append((micros, len(text)))
            n += 1
            rel = str(path.relative_to(CACHE_DIR))
            if errors_of(diags):
                err += 1
                fp_files.append((rel, errors_of(diags)))
            else:
                seeds.append((text, rel))
            if warnings_of(diags):
                warn += 1
                warn_files.append((rel, warnings_of(diags)))
        results["sources"][source.name] = {"files": n, "error_files": err, "warning_files": warn}
        print(f"{source.name:26s} {n:6d} {err:10d} {warn:11d}")
    total = sum(v["files"] for v in results["sources"].values())
    print(f"{'TOTAL':26s} {total:6d} {len(fp_files):10d} {len(warn_files):11d}")
    for rel, diags in fp_files[: args.list]:
        print(f"  FP  {rel}: " + "; ".join(show(d) for d in diags[:2]))
    if warn_files:
        print(f"  warnings ({sum(len(d) for _, d in warn_files)} in {len(warn_files)} files):")
        by_code = collections.Counter(d["code"] for _, ds in warn_files for d in ds)
        print("   ", dict(by_code))
        for rel, diags in warn_files[: args.list]:
            print(f"  W   {rel}: " + "; ".join(show(d) for d in diags[:2]))

    # --- 2. reference cases ------------------------------------------------------
    print("\n== reference cases (Databricks SQL docs) ==")
    cases = load_reference(corpus / "corpus" / "reference")
    parse_fp: list[tuple[str, list[dict]]] = []
    reject = collections.Counter()
    for case in cases:
        diags, _ = qc.check(case.sql, case.id)
        if case.verdict == "must-parse":
            if errors_of(diags):
                parse_fp.append((case.id, errors_of(diags)))
            reject["parse_total"] += 1
            reject["parse_warn"] += bool(warnings_of(diags))
        else:
            reject["reject_total"] += 1
            reject["reject_error"] += bool(errors_of(diags))
            reject["reject_any"] += bool(diags)
    print(f"must-parse: {reject['parse_total'] - len(parse_fp)}/{reject['parse_total']} clean "
          f"({len(parse_fp)} false positives, {reject['parse_warn']} with warnings)")
    print(f"must-reject: {reject['reject_error']}/{reject['reject_total']} flagged as errors, "
          f"{reject['reject_any']}/{reject['reject_total']} with any finding "
          "(grammar-level omissions: not a target)")
    for cid, diags in parse_fp[: args.list]:
        print(f"  FP  {cid}: " + "; ".join(show(d) for d in diags[:2]))
    results["reference"] = dict(reject, false_positives=[c for c, _ in parse_fp])

    # --- 3. mutation catch rate -------------------------------------------------
    print("\n== mutations of clean corpus files (corpus mutate.py) ==")
    mutants = mutate_corpus(seeds, seed=args.seed, limit=args.mutations or None)
    by_kind: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    tiers: dict[str, str] = {}
    escapes: list = []
    originals = {origin: text for text, origin in seeds}
    raw_set = 0
    for m in mutants:
        # A quote or comment opener is still lexed inside a SET value, so those stay scored.
        if (m.tier == GUARANTEED and m.kind not in ("unterminated-string", "unclosed-comment")
                and in_raw_set(originals[m.origin], m.sql)):
            raw_set += 1
            continue
        diags, _ = qc.check(m.sql, m.origin)
        c = by_kind[m.kind]
        tiers[m.kind] = m.tier
        c["total"] += 1
        c["error"] += bool(errors_of(diags))
        c["any"] += bool(diags)
        if m.tier == GUARANTEED and not errors_of(diags) and len(escapes) < args.list:
            escapes.append((m.kind, m.origin, m.sql))
    print(f"{'kind':28s} {'tier':11s} {'total':>6s} {'errors':>7s} {'rate':>7s} {'+warn':>7s}")
    g_total = g_err = 0
    for kind, c in sorted(by_kind.items(), key=lambda kv: (tiers[kv[0]], kv[0])):
        rate = c["error"] / c["total"] * 100
        anyrate = c["any"] / c["total"] * 100
        print(f"{kind:28s} {tiers[kind]:11s} {c['total']:6d} {c['error']:7d} {rate:6.1f}% {anyrate:6.1f}%")
        if tiers[kind] == GUARANTEED:
            g_total += c["total"]
            g_err += c["error"]
    if g_total:
        print(f"{'GUARANTEED (scored)':28s} {'':11s} {g_total:6d} {g_err:7d} {g_err / g_total * 100:6.1f}%")
    print(f"(excluded {raw_set} 'guaranteed' mutants inside SET key = value, where Spark reads the value as raw text)")
    for kind, origin, sql in escapes:
        print(f"  ESCAPE {kind} {origin}")
    results["mutation"] = {k: dict(v, tier=tiers[k]) for k, v in by_kind.items()}
    results["mutation_excluded_raw_set"] = raw_set

    # --- 4. speed ------------------------------------------------------------------
    print("\n== speed (in-process check time per file, valid corpus) ==")
    micros = sorted(t for t, _ in timings)
    chars = sum(c for _, c in timings)
    total_ms = sum(micros) / 1000
    print(f"{len(micros)} files, {chars / 1e6:.1f}M chars: total {total_ms:.0f} ms, "
          f"median {statistics.median(micros):.0f} us, p95 {micros[int(len(micros) * .95)]:.0f} us, "
          f"max {micros[-1] / 1000:.1f} ms")
    results["speed"] = {"files": len(micros), "total_ms": total_ms,
                        "median_us": statistics.median(micros), "max_us": micros[-1]}
    qc.close()

    if args.sqlfluff_sample:
        from dbsqlparse.corpus.runners import SqlFluffRunner

        runner = SqlFluffRunner()
        sample = sorted(CACHE_DIR.glob("dbx-*/**/*.sql"))[: args.sqlfluff_sample]
        runner.check("SELECT 1", "<warmup>")
        t0 = time.perf_counter()
        for p in sample:
            runner.check(p.read_text(encoding="utf-8", errors="replace"), str(p))
        per = (time.perf_counter() - t0) / len(sample) * 1000
        import sqlfluff
        print(f"SQLFluff {sqlfluff.__version__} parse (in-process, warm, no rules) on {len(sample)} "
              f"dbx-* files: {per:.0f} ms per file")
        results["speed"]["sqlfluff_ms_per_file"] = per

    out = ROOT / "eval" / "results"
    out.mkdir(exist_ok=True)
    (out / "latest.json").write_text(json.dumps(results, indent=2))
    return 1 if fp_files or parse_fp else 0


if __name__ == "__main__":
    sys.exit(main())
